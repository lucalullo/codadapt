"""Forward build/loader prerequisites without forwarding account credentials."""
ALLOWED = frozenset({
    'PATH','SYSTEMROOT','WINDIR','COMSPEC','PATHEXT','PROGRAMFILES','PROGRAMFILES(X86)',
    'PROGRAMW6432','SYSTEMDRIVE','PROCESSOR_ARCHITECTURE','NUMBER_OF_PROCESSORS',
    'INCLUDE','LIB','LIBPATH','DISTUTILS_USE_SDK','MSSDK','SETUPTOOLS_USE_DISTUTILS',
    'VCTOOLSINSTALLDIR','VCTOOLSVERSION','VCTOOLSREDISTDIR','VCINSTALLDIR','VSINSTALLDIR',
    'VISUALSTUDIOVERSION','WINDOWSSDKDIR','WINDOWSSDKVERSION','WINDOWSSDKBINPATH',
    'WINDOWSSDKVERBINPATH','WINDOWSLIBPATH','UNIVERSALCRTSDKDIR','UCRTVERSION',
    'EXTENSIONSDKDIR','VSCMD_ARG_TGT_ARCH','VSCMD_ARG_HOST_ARCH',
    'SDKROOT','MACOSX_DEPLOYMENT_TARGET','DYLD_LIBRARY_PATH','DYLD_FALLBACK_LIBRARY_PATH',
    'LIBOMP_PREFIX','CPPFLAGS','LDFLAGS',
})

def forward_environment(source):
    return {key:value for key,value in source.items() if key.upper() in ALLOWED}
